// Generates THIRD-PARTY-NOTICES.md from the installed npm dependency trees (bff, web, e2e).
//   node scripts/third-party.mjs   (run `npm ci` in each package first)
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const rows = new Map();

function licenseOf(pkg) {
  const l = pkg.license ?? pkg.licenses;
  if (!l) return "UNKNOWN";
  if (typeof l === "string") return l;
  if (Array.isArray(l)) return l.map((x) => x.type ?? x).join(" OR ");
  return l.type ?? "UNKNOWN";
}

for (const part of ["bff", "web", "e2e"]) {
  const lock = join(root, part, "package.json");
  const modules = join(root, part, "node_modules");
  if (!existsSync(lock) || !existsSync(modules)) continue;
  const direct = JSON.parse(readFileSync(lock, "utf8"));
  const runtime = new Set(Object.keys(direct.dependencies ?? {}));
  const scan = (dir) => {
    for (const entry of readdirSync(dir)) {
      if (entry.startsWith(".")) continue;
      const full = join(dir, entry);
      if (entry.startsWith("@")) { scan(full); continue; }
      const manifest = join(full, "package.json");
      if (!existsSync(manifest)) continue;
      const pkg = JSON.parse(readFileSync(manifest, "utf8"));
      if (!pkg.name || !pkg.version) continue;
      const key = `${pkg.name}@${pkg.version}`;
      const row = rows.get(key) ?? { name: pkg.name, version: pkg.version, license: licenseOf(pkg), parts: new Set(), runtime: false };
      row.parts.add(part);
      if (runtime.has(pkg.name)) row.runtime = true;
      rows.set(key, row);
    }
  };
  scan(modules);
}

const sorted = [...rows.values()].sort((a, b) => a.name.localeCompare(b.name));
const counts = {};
for (const row of sorted) counts[row.license] = (counts[row.license] ?? 0) + 1;
const lines = [
  "<!-- SPDX-FileCopyrightText: 2026 OpenTrix ESM contributors -->",
  "<!-- SPDX-License-Identifier: Apache-2.0 -->",
  "",
  "# Third-party notices",
  "",
  "Generated by `scripts/third-party.mjs` from the installed npm trees. Direct runtime dependencies are marked **R**.",
  "Packages are used unmodified under their own licenses; their license texts ship inside each package.",
  "",
  "## License summary",
  "",
  ...Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([license, n]) => `- ${license}: ${n}`),
  "",
  "## Packages",
  "",
  "| Package | Version | License | Part | Direct runtime |",
  "| --- | --- | --- | --- | --- |",
  ...sorted.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${[...r.parts].join(", ")} | ${r.runtime ? "R" : ""} |`),
  "",
];
writeFileSync(join(root, "THIRD-PARTY-NOTICES.md"), lines.join("\n"));
console.log(`${sorted.length} packages; licenses:`, counts);
